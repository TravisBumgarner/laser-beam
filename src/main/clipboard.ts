import { execFile } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { app, clipboard } from 'electron'
import type { ClipEntry } from '../shared/api'

const MAX = 200

const file = () => path.join(app.getPath('userData'), 'clipboard.json')

export const listClips = (): ClipEntry[] => {
  try {
    return JSON.parse(fs.readFileSync(file(), 'utf8'))
  } catch {
    return []
  }
}

const write = (clips: ClipEntry[]) => {
  fs.mkdirSync(path.dirname(file()), { recursive: true })
  fs.writeFileSync(file(), JSON.stringify(clips.slice(0, MAX), null, 2))
}

export const deleteClip = (text: string) => {
  const clips = listClips().filter((c) => c.text !== text)
  write(clips)
  return clips
}

const record = (text: string) => {
  if (!text.trim()) return
  write([{ text, copiedAt: Date.now() }, ...listClips().filter((c) => c.text !== text)])
}

// Password managers tag secrets with these nspasteboard.org types; never store them.
const SKIP_TYPES = [
  'org.nspasteboard.ConcealedType',
  'org.nspasteboard.TransientType',
  'org.nspasteboard.AutoGeneratedType',
]
const isSecret = async () => {
  const found = await Promise.all(
    SKIP_TYPES.map((t) => clipboard.has(`electron application/osclipboard;format="${t}"`).catch(() => false)),
  )
  return found.some(Boolean)
}

// Polls the system clipboard, since macOS has no change event.
export const watchClipboard = async () => {
  let last = await clipboard.readText()
  setInterval(async () => {
    const text = await clipboard.readText()
    if (text === last) return
    last = text
    if (!(await isSecret())) record(text)
  }, 500).unref()
}

// Puts the entry back on the clipboard and pastes it into the frontmost app.
export const pasteClip = async (text: string) => {
  await clipboard.writeText(text)
  return new Promise<void>((resolve) => {
    record(text)
    execFile(
      'osascript',
      ['-e', 'delay 0.1', '-e', 'tell application "System Events" to keystroke "v" using command down'],
      () => resolve(),
    )
  })
}
